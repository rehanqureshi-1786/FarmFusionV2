def localize_disease_response(data: Dict[str, Any], lang: str) -> Dict[str, Any]:
    """Translate disease response dictionary into target language."""
    if not lang or lang == "en":
        return data

    result = dict(data)
    d_name = data.get("disease_name", "")
    d_lower = d_name.lower().replace("_", " ")

    # 1. Localize disease name
    for key, trans in DISEASE_TRANSLATIONS.items():
        if key in d_lower:
            result["disease_name"] = trans.get(lang, trans.get("hi", d_name))
            break

    # 2. Localize crop type
    c_name = data.get("crop_type", "")
    if c_name:
        c_lower = c_name.lower().replace("_", " ")
        for key, trans in CROP_TRANSLATIONS.items():
            if key in c_lower:
                result["crop_type"] = trans.get(lang, trans.get("hi", c_name))
                break

    # Helper function to localize single advice line
    def _translate_advice(text: str) -> str:
        if not text:
            return text
        text_l = text.lower()
        # Direct key match
        for key, trans in ADVICE_TRANSLATIONS.items():
            if key in text_l:
                return trans.get(lang, trans.get("hi", text))
        
        # Check prefix
        for prefix in ["biological", "chemical", "cultural"]:
            if text_l.startswith(f"{prefix}:"):
                body = text[len(prefix)+1:].strip()
                body_l = body.lower()
                matched_body = None
                for key, trans in ADVICE_TRANSLATIONS.items():
                    if key in body_l:
                        matched_body = trans.get(lang, trans.get("hi", body))
                        break
                p_trans = PREFIX_TRANSLATIONS.get(prefix, {}).get(lang, PREFIX_TRANSLATIONS.get(prefix, {}).get("hi", prefix))
                if matched_body:
                    if matched_body.startswith(p_trans):
                        return matched_body
                    return f"{p_trans}: {matched_body}"
                else:
                    return f"{p_trans}: {body}"
        return text

    # 3. Localize treatment suggestions
    if "treatment_suggestions" in data and isinstance(data["treatment_suggestions"], list):
        result["treatment_suggestions"] = [_translate_advice(sug) for sug in data["treatment_suggestions"]]

    # 4. Localize prevention tips
    if "prevention_tips" in data and isinstance(data["prevention_tips"], list):
        result["prevention_tips"] = [_translate_advice(prev) for prev in data["prevention_tips"]]

    # 5. Localize store recommendations subtitles
    if "store_recommendations" in data and isinstance(data["store_recommendations"], list):
        new_store = []
        for item in data["store_recommendations"]:
            item_copy = dict(item)
            sub = item.get("subtitle", "")
            if sub:
                sub_l = sub.lower()
                matched = False
                for key, trans in ADVICE_TRANSLATIONS.items():
                    if key in sub_l:
                        item_copy["subtitle"] = trans.get(lang, trans.get("hi", sub))
                        matched = True
                        break
                if not matched:
                    # Generic fallback translation for targeted/recommended active ingredients
                    if "active ingredient" in sub_l:
                        item_copy["subtitle"] = ADVICE_TRANSLATIONS["targeted active ingredient"].get(lang, ADVICE_TRANSLATIONS["targeted active ingredient"].get("hi", sub))
            new_store.append(item_copy)
        result["store_recommendations"] = new_store

    return result
