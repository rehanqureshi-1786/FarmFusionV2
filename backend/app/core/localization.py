def localize_text(template_dict: Dict[str, Dict[str, str]], key: str, language: str = "hi", **kwargs) -> str:
    """
    Safely retrieves and formats a localized template string.
    Falls back to Hindi ('hi') or English ('en') if target language is unavailable.
    """
    clean_lang = (language or "hi").strip().lower()
    entry = template_dict.get(key, {})
    
    # Try exact language, then Hindi, then English, then first available
    msg_template = entry.get(clean_lang) or entry.get("hi") or entry.get("en") or ""
    if not msg_template and entry:
        msg_template = next(iter(entry.values()))
        
    try:
        return msg_template.format(**kwargs)
    except Exception:
        return msg_template
